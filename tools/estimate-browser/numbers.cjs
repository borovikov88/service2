 assert(item(result,'material_sand').quantity===item(original,'material_sand').quantity,'toggle raw quantity');
 assert(item(result,'material_sand').amount==='6741.50','sand exact amount');
 assert(item(result,'material_rebar').amount==='135000.00','rebar estimated amount');
