 await qty('pump').fill('1.5');await qty('pump').press('Tab');assert(!await qty('pump').evaluate(el=>el.checkValidity()),'fractional pump rejected');
 assert(await qty('pump').inputValue()==='1.5','fractional pump not hidden');
 assert(await qty('material_sand').evaluate(el=>el.type)==='number','number input retained');
 assert(await qty('material_sand').evaluate(el=>el.getBoundingClientRect().width)<100,'compact mobile width');
 await qty('material_sand').focus();await qty('material_sand').press('ControlOrMeta+A');await qty('material_sand').pressSequentially('0,6');
 assert(await qty('material_sand').inputValue()==='0.6','typed comma normalized: '+await qty('material_sand').inputValue());
 await qty('material_sand').fill('12');await qty('material_sand').press('End');
