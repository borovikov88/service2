 const recalculated=page.waitForResponse(r=>r.url().includes('/estimates/api')&&r.request().postDataJSON()?.action==='recalculate');
 await page.locator('#pe-parameters button[type=submit]').click();const recalc=(await (await recalculated).json()).snapshot;
 assert(recalc.variants.economy.total===original.variants.economy.total,'no-op recalc total');
