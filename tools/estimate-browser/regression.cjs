const {chromium}=require('playwright');
(async()=>{
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1365,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8769/estimates/');
await page.waitForFunction(()=>document.querySelectorAll('[data-variant]').length===3);
console.log('initial three variants: OK');
if(await page.locator('[data-row="work_plaster"][data-field="quantity"]').inputValue()!=='')throw Error('Fresh unknown plaster charged');
await page.locator('[name=heating_types][value=electric]').check();
await page.locator('[name=heating_types][value=exchanger]').check();
await page.locator('[name=heating_types][value=heatpump]').check();
await page.locator('[name=bowl_height]').fill('1.7');
await page.locator('[name=wall_thickness]').fill('0.2');
await page.locator('[name=slab_thickness]').fill('0.2');
await page.locator('#pe-parameters button[type=submit]').click();
await page.waitForFunction(()=>!document.querySelector('#pe-parameters input').disabled);
if(!await page.locator('#pe-heating-fields').isVisible())throw Error('Heating fields hidden');
if(await page.locator('#pe-org').count())throw Error('Organization field remains');
for(const text of ['Циркуляционный насос первичного','Электромагнитный клапан первичного','Бетон чаши: плита']) if(!await page.getByText(text,{exact:false}).first().count())throw Error('Missing '+text);
console.log('three sources + concrete + accessories: OK');
await page.locator('[data-shop=solenoid_valve]').click();
await page.locator('#pe-catalog-dialog').waitFor({state:'visible'});
if(await page.locator('#pe-catalog-kind').inputValue()!=='solenoid_valve')throw Error('Wrong accessory category');
await page.mouse.click(5,5);
await page.locator('#pe-catalog-dialog').waitFor({state:'hidden'});
console.log('accessory catalogue / outside-close: OK');
await page.locator('[name=heating_types][value=exchanger]').uncheck();
await page.locator('#pe-parameters button[type=submit]').click();
await page.waitForFunction(()=>!document.querySelector('#pe-parameters input').disabled);
if(await page.locator('[data-shop=solenoid_valve]').count())throw Error('Disabled accessory still active');
await page.locator('[name=heating_types][value=exchanger]').check();
await page.locator('#pe-parameters button[type=submit]').click();
await page.waitForFunction(()=>!document.querySelector('#pe-parameters input').disabled);
if(await page.locator('[data-shop=solenoid_valve]').count()!==1)throw Error('Accessory not restored exactly once');
console.log('source disable/restore: OK');
await page.locator('[data-row="heater_exchanger"][data-field="quantity"]').fill('2');
await page.locator('[data-row="heater_exchanger"][data-field="quantity"]').press('Tab');
await page.waitForFunction(()=>document.querySelector('[data-row="circulation_pump"][data-field="quantity"]').value==='2.000');
if(await page.locator('[data-quantity-mode="heater_exchanger"]').textContent()!=='вручную')throw Error('Manual label missing');
if(await page.locator('[data-quantity-mode="circulation_pump"]').textContent()!=='авто')throw Error('Auto label missing');
await page.locator('[data-exclude-row="heater_exchanger"]').click();
await page.locator('[data-scope-choice="one"]').click();
await page.waitForFunction(()=>!document.querySelector('[data-shop="circulation_pump"]'));
await page.locator('details:has(#pe-excluded-content) > summary').click();
await page.locator('[data-restore-row="heater_exchanger"]').click();
await page.locator('[data-scope-choice="one"]').click();
await page.waitForFunction(()=>document.querySelector('[data-shop="circulation_pump"]'));
console.log('two exchangers -> two accessories, labels and exclusion restore: OK');
await page.locator('[data-edit="circulation_pump"]').click();
await page.locator('#pe-row-form [name=heating_parent]').selectOption('');
await page.locator('#pe-row-form button[type=submit]').click();
await page.waitForTimeout(800);
if(await page.locator('[data-row="circulation_pump"][data-field="quantity"]').inputValue()!=='')throw Error('Unlinked quantity must be unknown');
console.log('unlink accessory -> unknown quantity / validation: OK');
await page.locator('[data-edit="circulation_pump"]').click();
if(await page.locator('#pe-row-form [name=quantity]').inputValue()!=='')throw Error('Expected unknown quantity on reopen');
await page.locator('#pe-row-form [name=heating_parent]').selectOption('heater_exchanger');
// Click actual submit: browser constraint validation must not block this path.
await page.locator('#pe-row-form button[type=submit]').click();
await page.locator('#pe-row-dialog').waitFor({state:'hidden'});
await page.waitForFunction(()=>document.querySelector('[data-row="circulation_pump"][data-field="quantity"]')?.value==='2.000');
if(await page.locator('[data-quantity-mode="circulation_pump"]').textContent()!=='авто')throw Error('Rebind became manual');
if(await page.locator('[data-shop="circulation_pump"]').count()!==1)throw Error('Rebind duplicated accessory');
await page.locator('[data-edit="circulation_pump"]').click();
await page.locator('#pe-row-form [name=auto_quantity]').uncheck();
await page.locator('#pe-row-form [name=quantity]').fill('0');
const zeroValidated=page.waitForResponse(r=>r.request().method()==='POST' && r.request().postDataJSON()?.action==='validate');
await page.locator('#pe-row-form button[type=submit]').click();
await page.locator('#pe-row-dialog').waitFor({state:'hidden'});
await page.waitForFunction(()=>document.querySelector('[data-row="circulation_pump"][data-field="quantity"]')?.value==='0');
if(await page.locator('[data-quantity-mode="circulation_pump"]').textContent()!=='вручную')throw Error('Manual zero lost');
const zeroSnapshot=(await (await zeroValidated).json()).snapshot;
const zeroRow=zeroSnapshot.variants.economy.blocks.flatMap(b=>b.rows).find(r=>r.id==='circulation_pump');
if(zeroRow.quantity!=='0.000' || zeroRow.auto_quantity)throw Error('Server lost manual zero');
console.log('reopen -> rebind -> submit without quantity; auto2, no duplicates; manual0: OK');
await page.locator('.pe-technology > summary').click();
await page.locator('[name=tech_sand]').selectOption('on');
await page.locator('[name=tech_sand_thickness]').fill('0.1');
await page.locator('[name=tech_sand_projection]').fill('0.1');
await page.locator('#pe-parameters button[type=submit]').click();
await page.waitForFunction(()=>document.querySelector('[data-row="work_sand_base"][data-field="quantity"]')?.value==='40.000');
await page.locator('[name=tech_sand]').selectOption('');
await page.locator('#pe-parameters button[type=submit]').click();
await page.waitForFunction(()=>document.querySelector('[data-row="work_sand_base"][data-field="quantity"]')?.value==='');
console.log('technology on -> area40; unknown -> empty quantity: OK');

if(errors.length)throw Error(errors.join('\n'));
console.log('browser JS errors: 0');await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
